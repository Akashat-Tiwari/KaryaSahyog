export function getServiceById(id) {
  return SERVICES_CATALOG.find((service) => service.id === id) || null;
}

export function searchServices(query) {
  const q = String(query || '').trim().toLowerCase();
  if (!q) return [];
  return SERVICES_CATALOG.filter((service) => {
    const haystack = [
      service.name,
      service.categoryName,
      service.category,
      service.description,
      service.appliance,
    ]
      .filter(Boolean)
      .join(' ')
      .toLowerCase();
    return haystack.includes(q);
  });
}

